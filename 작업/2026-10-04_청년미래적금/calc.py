def table_fifty():
    m = MAX_M
    print("표: 월 50만원 3년 기준 유형별 만기 금액과 과세 적금 환산 금리(기본금리 5%, 기여금 이자 제외)")
    print("| 경우 | 기여금 비율 | 정부 기여금 | 원금 이자 | 원금 포함 합계 | 과세 적금 환산 금리 |")
    print("|---|---|---|---|---|---|")
    cases = [
        ("기여금 미대상", RATE["미대상"]),
        ("일반형", RATE["일반형"]),
        ("우대형", RATE["우대형"]),
        ("일반형, 6개월 납입 뒤 해지하고 재가입", readjust(RATE["일반형"], 6)),
        ("우대형, 6개월 납입 뒤 해지하고 재가입", readjust(RATE["우대형"], 6)),
        ("일반형, 12개월 납입 뒤 해지하고 재가입", readjust(RATE["일반형"], 12)),
    ]
    for name, rate in cases:
        g, i = contrib(m, rate), interest(m, BASE_R)
        print("| " + " | ".join([name, pct(rate), won(g), won(i), won(principal(m) + g + i),
                                 f"{taxable_equiv(g, i, m):.2f}%"]) + " |")
    print()


def notes():
    m = MAX_M
    print("# 본문에 쓰는 계산 숫자")
    print(f"일반형 기여금 한 달 꼴 = {contrib(m, RATE['일반형']) // MONTHS:,}원 · 우대형 = {contrib(m, RATE['우대형']) // MONTHS:,}원")
    print(f"원금 이자 한 달 꼴 = {interest(m, BASE_R) // MONTHS:,}원")
    print(f"월 50만원 × 12개월 = {m * 12:,}원 = 법정 연 납입한도 {LAW_CAP_YEAR:,}원")
    print(f"원문 예시 되짚기: (108만 + 202만) ÷ 0.846 = {float(F(310) / (1 - TAX)):.1f}만원 · ÷ 2,775만원 = {float(F(310) / (1 - TAX) / 2775 * 100):.1f}%")
    print(f"원문 우대형 7% 예시의 원금 이자 몫 = {interest(m, F(7, 100)):,}원(이자 211만원 중), 나머지 = {2_110_000 - interest(m, F(7, 100)):,}원")
