    print(f"최초 모집 신청 234.3만명 대비 최종 가입 138.5만명 = {138.5 / 234.3 * 100:.1f}%")
    print(f"우대형 재직 요건 29개월 / 36개월 = {29 / 36 * 100:.1f}%")
    print(f"가입부터 만기 한 달 전까지 {MONTHS - 1}개월 중 29개월 재직 → 중소기업 밖 기간 최대 {MONTHS - 1 - 29}개월")


