#!/usr/bin/env python3
"""청년미래적금 2차 — 유형별 소득 기준 · 일정 · 월 납입액별 원금·기여금·원금 이자 · 과세 적금 환산 금리 (B1011-1/1).
표준 라이브러리만. 실행하면 원고에 넣는 표 네 개를 마크다운 그대로 출력한다. 같은 입력이면 같은 출력.

입력(아래 상수, 2026-10-04 원문 기준):
  가입 연령 만 19~34세(병역 최대 6년 빼기), 월 1천원~50만원 자유 납입, 3년 만기
      금융위원회 보도자료 2026-09-16 「10월 7일부터 청년미래적금 2차 가입 신청을 받습니다」
      https://www.fsc.go.kr/no010101/87726  (I. 가입대상 · 소득기준 표 · 참고 비교표)
  기여금 6%(일반형) · 12%(우대형), 금리 3년 고정 기본 5% + 우대 최대 2~3%, 일정, 갈아타기 조정비율
      금융위원회 보도자료 2026-09-30 「10월 7일부터 2차 가입신청 시작!」
      https://www.fsc.go.kr/no010101/87820  (2. 세부내용 · 3. 가입·심사 일정 · 4. 유형별 · 5. 갈아타기 주석)
  이자소득 비과세 · 납입한도 연 600만원 · 계약기간 3년 · 2028.12.31까지 가입 · 총급여 7,500만원/종합소득 6,300만원
      조세특례제한법 제91조의25 제1항·제2항·제3항
      https://www.law.go.kr/LSW/lsSideInfoP.do?lsiSeq=284389&joNo=0091&joBrNo=25&docCls=jo&urlMode=lsScJoRltInfoR
  2027년 정부 예산안(국회 확정 전): 우대형 12% → 15%, 지방 중소기업 25% — 87726 I. 가입대상 끝 주석

공식(원 단위 정수, 원 미만 버림):
  원금 P = m × 36
  기여금 G = P × 비율                                   (예: 1,800만원 × 6% = 108만원, × 12% = 216만원 — 87820 예시와 같음)
  원금 이자 I = m × r × (36 × 37 ÷ 2) ÷ 12 = m × r × 55.5 (단리, 매월 같은 날 납입, 만기까지 둔다고 가정)
      → 비과세(제91조의25 제1항)라 세금 0. 기여금에 붙는 이자는 원문에 계산 방식이 없어 넣지 않는다.
  과세 적금 환산 금리 = (G + I) ÷ (1 − 0.154) ÷ (m × 55.5)
      87820 주석과 같은 방식(일반형 7%: 원금 1,800만원 + 세전이자 366만원 − 이자소득세 56만원 → 13.2%).
      이 스크립트는 기여금 이자를 빼므로 원문 값보다 조금 낮게 나온다.
  재가입 조정 비율 = 비율 × (36 − k) ÷ 36, k = 앞서 가입했던 개월 수(납입 중지 기간 포함) — 87820 5. 주석
기준일: 2026-10-04.
"""
from fractions import Fraction as F

MONTHS = 36
MAX_M = 500_000
TAX = F(154, 1000)                 # 이자소득세 14% + 지방소득세 1.4% (환산용)
RATE = {"미대상": F(0), "일반형": F(6, 100), "우대형": F(12, 100)}
BUDGET = {"우대형(예산안)": F(15, 100), "지방 중소기업(예산안)": F(25, 100)}   # 국회 확정 전
BASE_R = F(5, 100)                 # 기본금리 5%(우대 0 가정)
LAW_CAP_YEAR = 6_000_000           # 연 600만원

TESTS = [
    {"m": 500_000, "rate": F(6, 100), "r": F(5, 100), "want": (18_000_000, 1_080_000, 1_387_500)},
    {"m": 500_000, "rate": F(12, 100), "r": F(7, 100), "want": (18_000_000, 2_160_000, 1_942_500)},
    {"m": 100_000, "rate": F(6, 100), "r": F(5, 100), "want": (3_600_000, 216_000, 277_500)},
    {"m": 300_000, "rate": F(12, 100), "r": F(5, 100), "want": (10_800_000, 1_296_000, 832_500)},
]


def principal(m):
    return m * MONTHS


def contrib(m, rate):
    return int(principal(m) * rate)


def interest(m, r):
    return int(F(m) * r * F(MONTHS * (MONTHS + 1), 2) / 12)


def taxable_equiv(g, i, m):
    """과세 단리 적금 환산 금리(%)."""
    return float((F(g + i) / (1 - TAX) / (F(m) * F(MONTHS * (MONTHS + 1), 2) / 12)) * 100)


def readjust(rate, k):
    return rate * (MONTHS - k) / MONTHS


def won(x):
    return f"{x:,}원"


def pct(x):
    return f"{float(x * 100):g}%"


def selftest():
    for t in TESTS:
        got = (principal(t["m"]), contrib(t["m"], t["rate"]), interest(t["m"], t["r"]))
        assert got == t["want"], (t, got)
    assert readjust(F(6, 100), 6) == F(5, 100)
    assert MAX_M * 12 == LAW_CAP_YEAR
    # 원문 예시 되짚기(일반형 7%: 원금 이자 + 기여금 이자 = 202만원 → 세전 366만원 → 13.2%)
    assert round(float(F(108 + 202) / (1 - TAX)), 0) == 366
    assert round(float(F(108 + 202) / (1 - TAX) / F(2775) * 100), 1) == 13.2


