def d(md):
    return dt.date(Y, *md)


def fmt(md):
    x = d(md)
    return f"{x.month}월 {x.day}일({WD[x.weekday()]})"


def short(name):
    return name.replace("기업인수목적", " 스팩")


def won(n):
    return f"{n:,}원"


def locked(r):
    return (d(r[5]) - d(r[4])).days


def min_dep(r, price):
    return price * r[7] * r[8] // 100


def holidays_between(a, b):
    return [x for x in (a + dt.timedelta(k) for k in range(1, (b - a).days)) if x in HOLIDAYS]


