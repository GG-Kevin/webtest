#!/usr/bin/env python3
"""순자산 상위 10% — 분위 경계값·연령대별 평균과 중앙값·독자 대입 계산 (표준 라이브러리만)

원문(모두 2026-10-03에 직접 열어 확인):
  - 국가데이터처 「2025년 가계금융복지조사 결과」 보도자료(게시 2025-12-04)
    https://mods.go.kr/board.es?mid=a10301040300&bid=215&act=view&list_no=439535
  - 같은 보도자료 부록 통계표 12 「순자산, 가구소득 분위별 평균, 점유율 및 경계값」(정책브리핑 문서 보기 결과 쪽)
    https://www.korea.kr/docViewer/result/2026.02/11/60111750b2cf47111010eaba7725fe7a/60111750b2cf47111010eaba7725fe7a.files/6.xhtml
  - 같은 부록 통계표 1~10(8. 순자산의 분포 · 2. 자산의 분포 · 5. 부채의 분포 · 7. 임대보증금)
    https://www.korea.kr/docViewer/result/2026.02/11/60111750b2cf47111010eaba7725fe7a/60111750b2cf47111010eaba7725fe7a.files/4.xhtml
기준일: 자산·부채·순자산은 2025년 3월 31일(조사 기준시점). 단위는 모두 만원(원문 단위).
정의: 순자산 = 자산 - 부채(부록2 항목분류 체계). P90 = 하위 90% 경계값 = 상위 10%가 시작하는 금액.
공식:
  - 순자산 = 자산 - 부채
  - 독자의 위치 = 원문 경계값 P10~P90 중 「P_k <= 순자산 < P_(k+1)」인 k를 찾아 「상위 (100-10(k+1))~(100-10k)%」로 읽는다
  - 평균÷중앙값 배율, 증감률 = (올해-작년)/작년×100, 구성비 = 항목/합계×100 (소수 첫째 자리 반올림)
같은 입력이면 같은 출력이다. 원고 표의 숫자는 모두 이 출력에서 가져온다.
"""

# ---- 원문 숫자 (만원) ----
P2025 = {10: 1210, 20: 5108, 30: 10296, 40: 16472, 50: 23860, 60: 33050, 70: 46180, 80: 69380, 90: 110020}
P90_2024 = 104592
P10_2024 = 1334
MEAN = {"자산": 56678, "부채": 9534, "순자산": 47144}
AGE = [  # (연령대, 순자산 평균, 순자산 중앙값) — 통계표 8. 순자산의 분포
    ("39세 이하", 21950, 12640),
    ("그중 30~39세", 25060, 15585),
    ("40~49세", 48389, 28384),
    ("50~59세", 55161, 31685),
    ("60세 이상", 53591, 25000),
    ("전체 가구", 47144, 23860),
]
TOP20 = {  # 순자산 5분위(상위 20%) 가구 평균 — 통계표 2·4·5·7·8
    "자산": 174590, "실물자산": 140025, "부동산": 133828, "거주주택": 68677, "거주주택이외": 65152,
    "금융자산": 34565, "부채": 22505, "임대보증금": 9932, "순자산": 152085,
}
EXAMPLES = [  # 독자 대입 (자산, 부채) 만원 — 가정
    ("자산 3억 · 부채 1억", 30000, 10000),
    ("자산 5억 · 부채 1억", 50000, 10000),
    ("자산 10억 · 부채 3억", 100000, 30000),
    ("자산 15억 · 부채 3억", 150000, 30000),
]


def won(man):
    """만원 정수 → 「11억 20만원」「6억 9,380만원」「1,210만원」"""
    man = int(round(man))
    sign = "-" if man < 0 else ""
    man = abs(man)
    eok, rest = divmod(man, 10000)
    if eok and rest:
        return f"{sign}{eok}억 {rest:,}만원"
    if eok:
        return f"{sign}{eok}억원"
    return f"{sign}{rest:,}만원"


def pct(a, b):
    return round(a / b * 100, 1)


def position(net):
    """원문 경계값으로 읽은 위치 문자열"""
    ks = sorted(P2025)
    if net >= P2025[90]:
        return "P90 이상 · 상위 10% 안"
    if net < P2025[10]:
        return "P10 미만 · 하위 10% 안"
    for a, b in zip(ks, ks[1:]):
        if P2025[a] <= net < P2025[b]:
            return f"P{a}~P{b} 사이 · 상위 {100 - b}~{100 - a}%"
    return "-"


def compute(자산, 부채):
    net = 자산 - 부채
    return {"순자산": net, "상위10문턱까지": P2025[90] - net}


def main():
    print("## 표1 순자산 분위 경계값(2025년 3월 말)")
    print("| 경계 | 뜻 | 순자산 경계값 |")
    print("|---|---|---|")
    for k in sorted(P2025, reverse=True):
        print(f"| P{k} | 이 금액부터 상위 {100 - k}% | {won(P2025[k])} |")
    print()
    print(f"- P90 2024년 {won(P90_2024)} → 2025년 {won(P2025[90])}: {won(P2025[90] - P90_2024)} 증가, 증감률 {pct(P2025[90] - P90_2024, P90_2024)}%")
    print(f"- P10 2024년 {won(P10_2024)} → 2025년 {won(P2025[10])}: 증감률 {pct(P2025[10] - P10_2024, P10_2024)}%")
    print(f"- P90 ÷ P50(중앙값) = {P2025[90] / P2025[50]:.2f}배")
    print(f"- P90 - P80 = {won(P2025[90] - P2025[80])}")
    print(f"- P90 ÷ 40~49세 중앙값 = {P2025[90] / AGE[2][2]:.2f}배 (약 {P2025[90] / AGE[2][2]:.1f}배)")
    print(f"- 평균 순자산 {won(MEAN['순자산'])} = 자산 {won(MEAN['자산'])} - 부채 {won(MEAN['부채'])} (검산 {won(MEAN['자산'] - MEAN['부채'])})")
    print(f"- 평균 - 중앙값 = {won(MEAN['순자산'] - P2025[50])}, 평균 ÷ 중앙값 = {MEAN['순자산'] / P2025[50]:.2f}배")
    print()
    print("## 표2 가구주 연령대별 순자산 평균과 중앙값(2025년 3월 말)")
    print("| 가구주 연령 | 평균 | 중앙값 | 평균 ÷ 중앙값 |")
    print("|---|---|---|---|")
    for name, mean, med in AGE:
        print(f"| {name} | {won(mean)} | {won(med)} | {mean / med:.2f}배 |")
    print()
    print("## 표3 독자 대입 계산(가정)")
    print("| 가정 | 순자산(자산 - 부채) | 원문 경계값으로 읽은 위치 | 상위 10% 문턱(11억 20만원)과의 차이 |")
    print("|---|---|---|---|")
    for name, a, d in EXAMPLES:
        r = compute(a, d)
        gap = r["상위10문턱까지"]
        gaps = f"{won(gap)} 모자람" if gap > 0 else f"{won(-gap)} 넘음"
        print(f"| {name} | {won(r['순자산'])} | {position(r['순자산'])} | {gaps} |")
    print()
    print("## 표4 순자산 상위 20%(5분위) 가구의 평균 자산·부채 구성(2025년 3월 말)")
    print("| 항목 | 평균 금액 | 비중 |")
    print("|---|---|---|")
    t = TOP20
    rows = [
        ("자산", t["자산"], "100.0% (자산 기준)"),
        ("실물자산", t["실물자산"], f"자산의 {pct(t['실물자산'], t['자산'])}%"),
        ("그중 부동산", t["부동산"], f"자산의 {pct(t['부동산'], t['자산'])}%"),
        ("그중 거주주택", t["거주주택"], f"자산의 {pct(t['거주주택'], t['자산'])}%"),
        ("그중 거주주택 이외 부동산", t["거주주택이외"], f"자산의 {pct(t['거주주택이외'], t['자산'])}%"),
        ("금융자산", t["금융자산"], f"자산의 {pct(t['금융자산'], t['자산'])}%"),
        ("부채", t["부채"], "100.0% (부채 기준)"),
        ("그중 임대보증금", t["임대보증금"], f"부채의 {pct(t['임대보증금'], t['부채'])}%"),
        ("순자산", t["순자산"], f"검산 {won(t['자산'] - t['부채'])}"),
    ]
    for name, v, s in rows:
        print(f"| {name} | {won(v)} | {s} |")
    print()
    print("## 검산")
    print(f"- 표4 자산 - 부채 = {won(t['자산'] - t['부채'])} / 원문 순자산 {won(t['순자산'])}")
    print(f"- 거주주택 + 거주주택 이외 = {won(t['거주주택'] + t['거주주택이외'])} / 원문 부동산 {won(t['부동산'])}(반올림 차이)")
    print(f"- 실물 + 금융 = {won(t['실물자산'] + t['금융자산'])} / 원문 자산 {won(t['자산'])}")


if __name__ == "__main__":
    main()
